def build_ch8(doc):
    h1(doc, "第8章　口座振替の説明")

    h2(doc, "8-1　【最重要】freee の「口座振替」は資金移動のこと")
    warn(doc, "世間一般でいう「口座振替」（電気代などが銀行から自動引き落としされること）と、"
              "freee の「口座振替」は意味が違います。"
              "freee の「口座振替」は、freee に登録した自分の口座と口座の間でお金が動いたときに使う機能です。"
              "銀行引き落としで経費を払った場合や、売掛金が入金された場合は、"
              "「口座振替」ではなく、ふつうの取引登録（第2章）や未決済取引の消込（第7章）で処理します。")
    para(doc, "freee は「口座振替」を、費用や売上の計上ではなく、社内の口座間で残高が動いただけの処理として扱います。"
              "ここを取り違えると、経費や売上が水増しされてしまいます。")

    h2(doc, "8-2　「口座振替」として登録するもの")
    bullets(doc, ["A銀行からB銀行への資金移動",
                  "現金の引き出し・預け入れ",
                  "クレジットカード利用分の銀行からの引き落とし",
                  "Amazon など購入履歴を同期しているサービスへの支払い",
                  "レジなど売上データを同期しているサービスから銀行口座への入金",
                  "交通系ICカード・電子マネーへのチャージ",
                  "小口現金への補充",
                  "役員借入金・立替金を口座として管理している場合の借入・返済"])

    h2(doc, "8-3　手動で登録する（どちらの口座も同期していない場合）")
    steps(doc, [
        "［取引入力］メニュー →［収入・支出形式（取引の一覧・登録）］を開き、［口座振替］タブをクリックします。",
        "「振替日」にお金が動いた日を入れます。",
        "「振替元口座」と「振替先口座」を選びます。",
        "「金額」を入力します。",
        "手数料が発生した場合は「手数料」欄に入力します（支払手数料として計上され、振替元の残高から引かれます）。",
        "［振替］ボタンをクリックします。",
    ])
    point(doc, "手数料の勘定科目や税区分を変えたい場合、または複数種類の手数料・受取利息を分けて記帳したい場合は、"
               "［詳細登録］→［手数料・受取利息等］から入力します。")

    h2(doc, "8-4　自動で経理から登録する（口座を同期している場合）")
    steps(doc, [
        "［取引入力］メニュー →［自動で経理］をクリックします。",
        "振替元の明細の色付き部分、または［詳細］ボタンをクリックします。",
        "画面上部の［口座振替・カード引き落とし］タブをクリックします。",
        "出金明細なら「振替先口座」を、入金明細なら「振替元口座」を選びます"
        "（現金の引き出し・預け入れなら「現金」を選びます）。",
        "必要に応じて「備考」を入力します。",
        "手数料が発生していれば「手数料」欄に入力し、下に表示される「送金額」が正しいことを確認します。",
        "［登録（Ctrl + Enter）］ボタンをクリックします。",
        "振替先の明細も取り込まれている場合は、その明細の［▼］ボタン →［明細を無視］をクリックします。",
    ])

    h2(doc, "8-5　両方の口座に明細が出たときは片方を「無視」する")
    para(doc, "A銀行からB銀行へ振り替えると、A銀行に出金明細、B銀行に入金明細の2件が取り込まれます。"
              "両方とも登録すると二重になるため、片方だけを登録してもう片方は「無視」します。")
    point(doc, "無視するのは「振替先の入金明細」の方をおすすめします。"
               "手数料の履歴は通常「振替元の出金明細」にだけ残るため、"
               "振替元の側で登録しておくと手数料の確認が楽になります。"
               "なお「口座振替マッチング機能」を使うと、片方を登録すると同時にもう片方が自動で無視されます。")

    h2(doc, "8-6　パターン早見表")
    table(doc,
          ["振替元(A)の出金明細", "振替先(B)の入金明細", "どう登録するか"],
          [["なし", "なし", "手動で「A→B」の口座振替を登録する（8-3）"],
           ["あり", "なし", "Aの出金明細から［口座振替・カード引き落とし］タブで登録する"],
           ["なし", "あり", "Bの入金明細から［口座振替・カード引き落とし］タブで登録する"],
           ["あり", "あり", "Aの出金明細で登録し、Bの入金明細は「無視」する"]],
          widths=[38, 38, 94])

    h2(doc, "8-7　現金の引き出し・預け入れ")
    bullets(doc, ["現金を銀行に預け入れた … 銀行の入金明細から、「振替元口座」に「現金」を選んで登録します"
                  "（現金には明細がないので、無視の操作は不要です）",
                  "銀行から現金を引き出した … 銀行の出金明細から、「振替先口座」に「現金」を選んで登録します。"
                  "手数料220円がかかった場合は「手数料」欄に220と入力し、送金額が正しくなることを確認します"])
    para(doc, "引き出し額と手数料が別々の出金明細として取り込まれている場合は、"
              "引き出し額は［口座振替・カード引き落とし］タブで、手数料は［取引登録］タブで「支払手数料」として登録します。")

    h2(doc, "8-8　クレジットカードの引き落とし")
    para(doc, "カードの利用分は、カード口座の明細から［取引登録］で経費として登録します。"
              "そのうえで、銀行から引き落とされたときの出金明細は「口座振替」として処理します。")
    steps(doc, [
        "カード口座の各明細を［自動で経理］で経費として登録します（第2章）。",
        "銀行口座の引き落とし明細を［詳細］→［口座振替・カード引き落とし］タブで開きます。",
        "「振替先口座」に、そのクレジットカードの口座を選びます。",
        "［登録（Ctrl + Enter）］ボタンをクリックします。",
    ])
    warn(doc, "銀行の引き落とし明細を「取引登録」で経費にしてはいけません。"
              "カード利用時にすでに経費を計上しているため、経費が二重になります。"
              "なお、カードの支出明細で誤って「振替先口座」に銀行口座を選ぶと、freee が警告を出してくれます。")

    h2(doc, "8-9　振替伝票との違い")
    para(doc, "freee には仕訳の形で直接入力する「振替伝票」もありますが、日常の記帳では使いません。")
    table(doc,
          ["", "取引・口座振替", "振替伝票"],
          [["入力の形", "freee の「取引」形式", "借方・貸方の仕訳形式"],
           ["場所", "［取引入力］の各メニュー", "［取引入力］→［振替伝票］"],
           ["主な用途", "日々の記帳のほとんど", "決算整理仕訳、修正仕訳、資産の売却、他社ソフトからの乗り換え"],
           ["入金・支払管理レポート", "反映される", "未決済取引を作らないと反映されない"]],
          widths=[34, 62, 74])
    point(doc, "freee は、特別な理由がない場合は「取引」形式で登録することを推奨しています。"
               "振替伝票を使う場面は、基本的に税理士が決算で使うときだと考えてください。")
    pagebreak(doc)
