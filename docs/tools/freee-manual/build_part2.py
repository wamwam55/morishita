def build_ch3(doc):
    h1(doc, "第3章　入力ルールの作成方法（自動登録ルール）")
    para(doc, "毎月同じ内容の明細（家賃、電気代、通信費など）は、"
              "1度ルールを作れば次からは自動で勘定科目が入ります。freee を楽にする最大のポイントです。")

    h2(doc, "3-1　自動登録ルールとは")
    para(doc, "「こういう明細が来たら、こう処理する」という約束ごとです。次の2つを決めます。")
    bullets(doc, ["適用する条件 … どんな内容の明細に対して",
                  "一致したときに行う処理 … どんな処理をするか"])

    h2(doc, "3-2　作り方A　実際の明細から作る（おすすめ）")
    para(doc, "毎日の作業の流れの中で作れるので、いちばん自然で間違いがありません。")
    steps(doc, [
        "［自動で経理］の画面で、ルールにしたい明細の［詳細］ボタンをクリックします。",
        "勘定科目など、必要な内容を入力します。",
        "「自動登録ルールとして設定」のチェックボックスにチェックを入れて、［登録（Ctrl + Enter）］をクリックします。",
        "入力した内容が引き継がれた状態で「自動登録ルールの作成」画面が開きます。",
        "条件や処理を必要に応じて直し、［作成する］ボタンをクリックします。",
    ])

    h2(doc, "3-3　作り方B　設定画面から作る")
    steps(doc, [
        "［入力効率化］メニュー →［自動登録ルール］を開き、左上の［新規作成］ボタンをクリックします。",
        "「自動登録ルールを適用する条件」を設定します。",
        "「上記の条件に一致したとき行う処理」を設定します。",
        "内容を確認して、画面右下の［作成する］ボタンをクリックします。",
    ])

    h2(doc, "3-4　条件で指定できること")
    table(doc,
          ["項目", "設定内容"],
          [["収支区分", "［収入］または［支出］"],
           ["取引口座", "特定の口座、または［すべての口座・カード］"],
           ["取引内容", "文字を入力し、［部分一致］／［前方一致］／［後方一致］／［完全一致］／［指定なし］から選ぶ"],
           ["金額", "最小値・最大値を入力（同じ金額を入れると「その金額ちょうど」の条件になります）"],
           ["優先度", "数字が大きいほど優先されます。とくに無ければ「0」を入れます"]],
          widths=[26, 144])
    point(doc, "取引内容は「部分一致」がいちばん使いやすいです。"
               "たとえば電気代なら「関西電力」だけを部分一致で指定すれば、後ろに付く番号が毎月変わっても効きます。")

    h2(doc, "3-5　【重要】「推測する」と「登録する」の違い")
    table(doc,
          ["種類", "動き", "向いている場面"],
          [["○○を推測する",
            "勘定科目などを自動で入れるところまで。［登録］は自分で押します",
            "金額が毎月変わるもの、念のため目視したいもの。まずはこちらから始めるのが安全です"],
           ["○○を登録する",
            "確認なしで自動的に登録まで済ませます。［自動で経理］の画面にも出てきません",
            "毎月まったく同じ内容（家賃など）で、確認が不要と言い切れるもの"]],
          widths=[32, 78, 60])
    warn(doc, "「登録する」にすると、その明細は［自動で経理］の画面に現れません。"
              "設定を間違えると、気づかないまま誤った勘定科目で記帳され続けます。"
              "慣れるまではすべて「推測する」で運用することをおすすめします。")
    para(doc, "設定できる処理には、ほかに「振替を推測する／登録する」「無視する取引を推測する／登録する」"
              "「プライベート取引を推測する／登録する」「未決済取引の消込をする」などがあります。")

    h2(doc, "3-6　優先度（ルールがぶつかったとき）")
    bullets(doc, ["優先度は数字が大きいほど優先されます（マイナスも入れられます）",
                  "思ったのと違うルールが効いてしまうときは、①不要なルールが残っていないか ②ルール同士がぶつかっていないか、を確認します",
                  "細かい条件のルールほど優先度を大きく、ざっくりした条件のルールほど小さく、が基本です"])

    h2(doc, "3-7　作ったルールを既存の明細にも適用する")
    h3(doc, "未登録の明細すべてに適用する")
    steps(doc, ["［取引入力］→［自動で経理］を開きます。",
                "画面左上の［自動登録ルールの適用］ボタン →［最新の自動登録ルールを適用］をクリックします。",
                "確認メッセージで［登録する］ボタンをクリックします。"])
    h3(doc, "特定の明細だけに適用する")
    steps(doc, ["［会計帳簿］メニュー →［明細の一覧］を開きます。",
                "画面上部の検索条件で明細を絞り込みます。",
                "対象にチェックを入れ、［一括操作］→［自動登録ルール］をクリックします。",
                "確認画面で［適用する］ボタンをクリックします。"])

    h2(doc, "3-8　確認・修正・削除")
    bullets(doc, ["一覧を見る … ［入力効率化］→［自動登録ルール］",
                  "修正する … 一覧でルールの行をクリックし、直したあと［設定する］ボタン",
                  "削除する … 一覧の右端の［削除］ボタン。まとめて消すときはチェックを入れて［一括操作］→［一括削除］",
                  "どのルールが効いたか調べる … ［自動で経理］の明細内にある「自動登録ルールに合致」のリンクをクリック"])

    h2(doc, "3-9　最初に作っておくと効くルールの例")
    table(doc,
          ["取引内容（部分一致）", "勘定科目", "処理"],
          [["家賃・賃料の振込先名", "地代家賃", "推測する"],
           ["電力会社名", "水道光熱費", "推測する"],
           ["携帯電話会社名・プロバイダ名", "通信費", "推測する"],
           ["ETC・交通系ICのチャージ以外の利用", "旅費交通費", "推測する"],
           ["振込手数料・ATM手数料", "支払手数料", "推測する"],
           ["社会保険料・年金", "法定福利費（または預り金）", "推測する"],
           ["税金の納付（○○税）", "租税公課", "推測する"]],
          widths=[70, 60, 40])
    point(doc, "最初の1か月は「同じ明細が2回目に出てきたらルールを作る」と決めておくと、"
               "3か月目にはほとんどの明細が自動で埋まるようになります。")
    pagebreak(doc)


