def checkbox_line(doc, text, indent=6):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Mm(indent + 6)
    pf.first_line_indent = Mm(-6)
    spacing(p, after=3)
    set_jp(p.add_run("□　"), 11, True, ACCENT)
    set_jp(p.add_run(text), 10.5)


