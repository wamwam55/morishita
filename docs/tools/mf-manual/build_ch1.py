# -*- coding: utf-8 -*-
"""第1章 最初にやること（初期設定）"""
from common import (h1, h2, h3, para, steps, bullets, point, warn, table, pagebreak)


def build(doc):
    h1(doc, "第1章　最初にやること（初期設定）")
    para(doc, "ここは最初の1回だけです。ここを飛ばすと後で数字が合わなくなるので、"
              "面倒でも先に済ませてください。所要時間は30分ほどです。")

    h2(doc, "1-1　先に手元に用意するもの")
    table(doc,
          ["用意するもの", "何に使うか"],
          [["前期の決算書（法人）／前年の確定申告書（個人）", "開始残高の入力に使います"],
           ["使っている勘定科目・補助科目の一覧", "科目の設定をそろえるために使います"],
           ["ネットバンキング・カードのログイン情報", "データ連携（第2章）に使います"]],
          widths=[76, 94], size=9.5)

    point(doc, "前期の決算書がお手元にない場合は、当事務所へご連絡ください。"
               "開始残高の入力はこちらで代行することもできます。")

    h2(doc, "1-2　事業者の設定")
    steps(doc, [
        "［各種設定］＞［事業者］を開きます。",
        "「（必須）」と表示されている項目をすべて埋めます。",
        "消費税の設定（課税事業者か免税事業者か、税抜経理か税込経理か）を選びます。",
        "保存します。",
    ])
    warn(doc, "消費税の設定は、あとから変えると過去の仕訳の税額計算に影響します。"
              "「課税事業者かどうか」「税抜経理か税込経理か」がわからない場合は、"
              "設定せずに当事務所へお問い合わせください。ここだけは推測で決めないでください。")

    h2(doc, "1-3　開始残高の入力")
    para(doc, "開始残高とは、開業日または会計期間の初日時点での資産・負債・純資産の残高です。"
              "これを入れておかないと、預金残高も売掛金も正しく表示されません。")
    steps(doc, [
        "［各種設定］＞［開始残高］を開きます。",
        "前期の決算書（貸借対照表）を見ながら、「資産の部」「負債の部」「純資産の部」に金額を入力します。",
        "画面下の「借方合計」と「貸方合計」が一致しているか確認します。",
        "［保存］をクリックします。",
        "確認メッセージで［OK］をクリックします。",
    ])
    para(doc, "科目数が多い場合は、CSVでまとめて入れることもできます。"
              "［CSVでの開始残高の編集］→［ダウンロード］→ Excelで編集 →［ファイルを選択］→［インポート］の順です。")

    warn(doc, "借方合計と貸方合計が一致しないと保存できません。1円でも合わないときは、"
              "決算書の数字を見落としていないか（未払金、預り金、繰越利益剰余金など）を確認してください。")

    h2(doc, "1-4　勘定科目を自社に合わせる")
    para(doc, "標準の科目のままでも使えますが、よく使う科目や取引先別の管理をしたい場合は調整します。")
    steps(doc, [
        "［各種設定］＞［勘定科目］を開きます。",
        "「貸借対照表」「損益計算書」のタブを切り替えて、対象の場所を表示します。",
        "科目を足すときは［＋勘定科目追加］をクリックし、決算書科目 → 勘定科目名 → 税区分 → 検索キーの順に入力して［登録］。",
        "取引先別・口座別に分けたいときは［＋補助科目追加］を使います。",
    ])

    table(doc,
          ["階層", "意味", "例"],
          [["決算書科目", "決算書に印字される大きなくくり", "現金及び預金"],
           ["勘定科目", "ふだん使う科目", "普通預金"],
           ["補助科目", "さらに細かく分けたいとき", "A銀行、B銀行"]],
          widths=[30, 70, 70], size=9.5)

    point(doc, "普通預金に「A銀行」「B銀行」の補助科目を作っておくと、"
               "［残高試算表］で口座ごとの残高が見られるようになります。口座が2つ以上ある方は必ず設定してください。")

    warn(doc, "勘定科目の設定は事業者全体で共通です。変更すると過去の仕訳や決算書にも影響します。"
              "初期から入っている科目は削除できません。使わない科目は無視して構いません。")

    h3(doc, "この章でできるようになること")
    bullets(doc, ["事業者情報・消費税の設定が終わっている",
                  "開始残高が入り、借方と貸方が一致している",
                  "口座ごとの補助科目ができている"], keep=True)
