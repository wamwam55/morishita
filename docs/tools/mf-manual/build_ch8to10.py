        "「請求書に対応した入金予定の仕訳」を「作成する」にします。",
        "取引先ごとに売掛金を分けたい場合は「取引先に応じた補助科目」も「作成する」にします。",
        "「売上計上日のデフォルト値」を選びます（請求書作成日／請求日／当月末／前月末／前々月末）。",
